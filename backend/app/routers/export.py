from fastapi import APIRouter
from fastapi.responses import PlainTextResponse
from pydantic import BaseModel
from typing import Dict, Any

router = APIRouter(prefix="/export", tags=["Export"])


class ExportRequest(BaseModel):
    analysis_data: Dict[str, Any]
    format: str = "markdown"  # markdown or json


@router.post("")
def export_report(req: ExportRequest):
    data = req.analysis_data
    if req.format.lower() == "json":
        import json
        return PlainTextResponse(
            content=json.dumps(data, indent=2),
            media_type="application/json",
            headers={"Content-Disposition": f"attachment; filename=research_scope_report.json"}
        )

    # Markdown export
    idea = data.get("idea", "Research Idea")
    domain = data.get("detected_domain", "Domain")
    eval_data = data.get("evaluation", {})
    acad = eval_data.get("academic", {})
    ind = eval_data.get("industry", {})
    soc = eval_data.get("societal", {})
    fut = eval_data.get("future_potential", {})
    comp = eval_data.get("composite_score", 0.0)
    gaps = data.get("gaps", [])
    similar_papers = data.get("similar_papers", [])
    explanation = data.get("explanation", {})

    md = f"""# Research Scope Analysis Report

**Generated:** {data.get("created_at", "N/A")}  
**Research Idea:** {idea}  
**Detected Domain:** {domain}  
**Overall Viability Score:** {comp}/100  

---

## 1. Multi-Dimensional Relevance Evaluation

| Dimension | Score | Rating | Primary Rationale |
| :--- | :--- | :--- | :--- |
| **Academic Relevance** | {acad.get('score', 0)}/100 | {acad.get('level', '')} | {acad.get('evidence', [''])[0] if acad.get('evidence') else ''} |
| **Industry Relevance** | {ind.get('score', 0)}/100 | {ind.get('level', '')} | {ind.get('evidence', [''])[0] if ind.get('evidence') else ''} |
| **Societal Relevance** | {soc.get('score', 0)}/100 | {soc.get('level', '')} | {soc.get('evidence', [''])[0] if soc.get('evidence') else ''} |
| **Future Potential** | {fut.get('score', 0)}/100 | {fut.get('level', '')} | {fut.get('evidence', [''])[0] if fut.get('evidence') else ''} |

---

## 2. Executive Synthesis & Findings

{explanation.get('executive_summary', '')}

### Similarity Insights
{explanation.get('similarity_insights', '')}

### Trend & Trajectory Insights
{explanation.get('trend_insights', '')}

### Research Gap Insights
{explanation.get('gap_insights', '')}

---

## 3. Identified Potential Research Gaps

"""
    for i, g in enumerate(gaps, 1):
        md += f"""### Gap {i}: {g.get('gap_title')} (Novelty: {g.get('novelty_score')}/100)
- **Concept Intersection:** {g.get('concept_a')} + {g.get('concept_b')}
- **Observed Frequency:** {g.get('co_occurrence_count')} co-occurring publications
- **Analysis:** {g.get('description')}
- **Suggested Direction:** {g.get('suggested_direction')}

"""

    md += """---

## 4. Top Related Literature

| Rank | Title | Year | Venue | Similarity | Citations |
| :--- | :--- | :--- | :--- | :--- | :--- |
"""
    for p in similar_papers[:10]:
        title = p.get('title', '').replace('|', '-')
        year = p.get('publication_year') or 'N/A'
        venue = (p.get('venue') or 'N/A').replace('|', '-')[:30]
        sim = f"{p.get('similarity_score', 0)}%"
        cits = p.get('citations', 0)
        rank = p.get('rank', 1)
        md += f"| {rank} | {title} | {year} | {venue} | {sim} | {cits} |\n"

    md += """
---
*Report generated by **Research Scope** — AI-Powered Scholarly Research Analysis Platform.*
"""

    return PlainTextResponse(
        content=md,
        media_type="text/markdown",
        headers={"Content-Disposition": "attachment; filename=research_scope_report.md"}
    )
